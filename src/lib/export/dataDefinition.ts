/**
 * Human-readable data definition of the aggregated-results package: one section per dataset with its
 * file, records, keys and variables (name, SAS name, type, length, description, origin), generated from
 * the same names and types as define.xml. define.xml stays the machine-readable definition; this page is
 * what a reviewer opens, and it does not depend on the CDISC stylesheet.
 */
import type { CombinedTable } from '@/lib/cdisc/datasetJson'
import { columnSasNames, datasetFiles, xmlEscape, type DatasetFormat } from '@/lib/cdisc/defineXml'
import { textLength } from '@/lib/cdisc/xpt'

export interface DataDefinitionInput {
  studyId: string
  studyTitle: string
  generatedAt: string
  tables: CombinedTable[]
  datasetFormat?: DatasetFormat
  /** e.g. "Dataset-JSON v1.1". */
  formatLabel: string
}

const TYPE: Record<string, string> = { string: 'text', integer: 'integer', double: 'float' }

export function buildDataDefinitionHtml(i: DataDefinitionInput): string {
  const xpt = i.datasetFormat === 'xpt'
  const files = datasetFiles(i.tables, i.datasetFormat)
  const e = xmlEscape
  const toc = i.tables.map((t) => `<li><a href="#${e(t.name)}">${e(files.get(t.name)!.sasName)}</a> — ${e(t.label)} (${t.rows.length})</li>`).join('')
  const sections = i.tables
    .map((t) => {
      const f = files.get(t.name)!
      const sas = columnSasNames(t)
      const keys = t.columns.filter((c) => c.primaryKey).map((c) => c.name)
      const rows = t.columns
        .map((c, ci) => {
          const length = c.dataType === 'string' ? (xpt ? textLength(t, ci) : c.length) : ''
          const origin = c.name === 'SITE_ID' ? 'Assigned from the StudyPack manifest siteId' : c.minCellCount ? 'Derived; subject to min-cell-count suppression (censored values reported as -minCellCount)' : 'Derived'
          return `<tr><td><code>${e(xpt ? sas[ci] : c.name)}</code></td><td><code>${e(xpt ? c.name : sas[ci])}</code></td><td>${TYPE[c.dataType] ?? c.dataType}</td><td>${length}</td><td>${c.primaryKey ? keys.indexOf(c.name) + 1 : ''}</td><td>${e(c.description || c.name.replace(/_/g, ' ').toLowerCase())}</td><td>${e(origin)}</td></tr>`
        })
        .join('')
      return `<section id="${e(t.name)}"><h2>${e(f.sasName)} — ${e(t.label)}</h2>
<p>File <code>${e(f.path)}</code> · ${t.rows.length} record(s) · Strategus table <code>${e(t.sourceTable)}</code>${t.module ? ` (${e(t.module)})` : ''} · ${keys.length ? `one record per ${e(keys.join(', '))}` : 'one record per site result row'}</p>
<table><tr><th>${xpt ? 'Variable' : 'Name'}</th><th>${xpt ? 'Strategus column' : 'SAS name'}</th><th>Type</th><th>Length</th><th>Key</th><th>Description</th><th>Origin</th></tr>${rows}</table></section>`
    })
    .join('\n')
  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><title>Data definition — ${e(i.studyId)}</title>
<style>body{font:14px/1.5 system-ui,sans-serif;max-width:1100px;margin:2rem auto;padding:0 1rem;color:#0f172a}table{border-collapse:collapse;width:100%;margin:.5rem 0 1.5rem}th,td{border:1px solid #cbd5e1;padding:.25rem .5rem;text-align:left;vertical-align:top}th{background:#f1f5f9}code{font-size:12px}h2{margin-top:2rem}</style></head>
<body><h1>Data definition — ${e(i.studyId)}</h1>
<p>${e(i.studyTitle)}. Generated by OHDSI Study Studio on ${e(i.generatedAt)}.</p>
<p>Aggregated results of a distributed network study on the OMOP Common Data Model (OHDSI Strategus), one dataset per Strategus result table, rows of the adopted sites concatenated with <code>SITE_ID</code>. The datasets are not SDTM or ADaM datasets. Files: ${e(i.formatLabel)}. The same structures are described for machines in <code>define.xml</code>.</p>
<ul>${toc}</ul>
${sections}
</body></html>
`
}
